"""Trace statistics for the paper, from the derived SETI@home sessions of the Failure Trace Archive (plan V9.2;
markers T08 and T15 in the manuscript).

The derived parquet files are gitignored data, so this module computes the statistics once from the release asset
``data-seti09-79bec54d`` and commits them with their hashes in ``docs/validation/trace-statistics.yaml``. The paper
reads only that summary, as ``paper_inputs`` reads the traces' provenance files.

    gh release download data-seti09-79bec54d -p 'sessions_*.parquet' -D data/traces/seti09
    uv run python -m experiments.analysis.traces
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
from typing import Any

import pandas as pd
import yaml
from scipy import stats
from voss.core.paths import REPO_ROOT

SUMMARY = REPO_ROOT / "docs" / "validation" / "trace-statistics.yaml"
PROVENANCE = REPO_ROOT / "configs" / "traces" / "seti09" / "provenance.yaml"
RELEASE = "data-seti09-79bec54d"


def _yaml(path: Path) -> dict[str, Any]:
    data: dict[str, Any] = yaml.safe_load(path.read_text())
    return data


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def _split(path: Path, week_s: float) -> dict[str, Any]:
    """Interval count, median and mean length, Weibull fit and mean available fraction of one trace week."""
    frame = pd.read_parquet(path)
    lengths = (frame["end_s"] - frame["start_s"]).to_numpy()
    lengths = lengths[lengths > 0]
    durations = frame.assign(duration=frame["end_s"] - frame["start_s"]).groupby("host")["duration"].sum()
    available = durations / week_s
    shape, _, scale = stats.weibull_min.fit(lengths, floc=0)
    return {
        "file": path.name,
        "sha256": _sha256(path),
        "intervals": len(frame),
        "hosts": int(frame["host"].nunique()),
        "median_h": float(pd.Series(lengths).median() / 3600),
        "mean_h": float(lengths.mean() / 3600),
        "weibull_shape": float(shape),
        "weibull_scale_h": float(scale / 3600),
        "available_frac": float(available.mean()),
    }


def compute(dev: Path, heldout: Path) -> dict[str, Any]:
    """The summary written to ``SUMMARY``; the hashes must be the release's (``provenance.yaml``)."""
    prov = _yaml(PROVENANCE)
    week_s = float(prov["params"]["week_s"])
    summary: dict[str, Any] = {
        "provenance": {
            "default": "trace",
            "note": f"generated by experiments.analysis.traces from {RELEASE}; do not edit",
        },
        "source": RELEASE,
        "trace": "configs/traces/seti09/provenance.yaml",
        "week_s": week_s,
        "splits": {"dev": _split(dev, week_s), "heldout": _split(heldout, week_s)},
        "published": {
            "source": "javadi2009seti",
            "table": 3,
            "note": "all hosts of the trace; the paper reports both fits and does not claim to reproduce this one",
            # literature: Javadi et al., MASCOTS 2009, Table 3 (all iid hosts)
            "weibull_shape": 0.3787,
            "weibull_scale_h": 3.0932,
        },
    }
    for split, name in (("dev", "sessions_dev.parquet"), ("heldout", "sessions_heldout.parquet")):
        assert summary["splits"][split]["sha256"] == prov["outputs"][name], f"{split} is not the release asset"
    return summary


def load() -> dict[str, Any]:
    return _yaml(SUMMARY)


def values(out: dict[str, float | int | str]) -> None:
    """Macros for the availability sentence (T08)."""
    summary = load()
    dev, held = summary["splits"]["dev"], summary["splits"]["heldout"]
    median_min = [dev["median_h"] * 60, held["median_h"] * 60]
    available = [dev["available_frac"] * 100, held["available_frac"] * 100]
    out["TraceIntervalMedianLoMin"] = round(min(median_min))
    out["TraceIntervalMedianHiMin"] = round(max(median_min))
    out["TraceAvailableLoPct"] = round(min(available))
    out["TraceAvailableHiPct"] = round(max(available))


def _num(value: float) -> str:
    return f"{value:.2g}"


def table() -> str:
    """Interval-length distribution of the two weeks against the published fit (T15)."""
    summary = load()
    dev, held = summary["splits"]["dev"], summary["splits"]["heldout"]
    rows = [
        "% Generated by experiments.analysis.paper_inputs; do not edit.",
        "Week & Intervals & Median (h) & Mean (h) & Shape & Scale (h) \\\\",
        "\\midrule",
    ]
    for label, split in (("Development", dev), ("Held-out", held)):
        rows.append(
            f"{label} & {split['intervals']:,}".replace(",", "{,}")
            + f" & {_num(split['median_h'])} & {_num(split['mean_h'])} & "
            + f"{_num(split['weibull_shape'])} & {_num(split['weibull_scale_h'])} \\\\"
        )
    published = summary["published"]
    rows.append(
        "Published fit & --- & --- & --- & "
        f"{_num(published['weibull_shape'])} & {_num(published['weibull_scale_h'])} \\\\"
    )
    rows.append("\\bottomrule")
    return "\n".join(rows) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dev", type=Path, default=Path("data/traces/seti09/sessions_dev.parquet"))
    parser.add_argument("--heldout", type=Path, default=Path("data/traces/seti09/sessions_heldout.parquet"))
    parser.add_argument("--out", type=Path, default=SUMMARY)
    args = parser.parse_args(argv)
    args.out.write_text(yaml.safe_dump(compute(args.dev, args.heldout), sort_keys=False))
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
