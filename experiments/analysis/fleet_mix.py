"""The calibrated fleet's survey mapping for the paper (plan V9.4, D-107, marker T14 in ``method.tex``): the weight of
each machine class, the share of hosts no calibrated machine represents well and the share that is not x86.

Read by ``experiments.analysis.paper_inputs`` (macros in ``inputs.tex``, the table ``fleet.tex``).
"""

from __future__ import annotations

from voss.core.config import load_config
from voss.core.paths import REPO_ROOT
from voss.world.machines import MachinesParams, Mix, load_hw, mem_bucket, survey_mix, survey_table

FLEET = REPO_ROOT / "configs" / "machines.yaml"


def fleet_mix() -> tuple[MachinesParams, Mix]:
    """Mix of the fleet overlay ``configs/machines.yaml`` (needs its survey under ``data/traces``)."""
    mp = MachinesParams.model_validate(load_config(FLEET).scenario.machines)
    return mp, survey_mix(survey_table(mp), {b: load_hw(b) for b in sorted(set(mp.bundles))}, mp.radius)


def values(out: dict[str, float | int | str]) -> None:
    mp, mix = fleet_mix()
    out["FleetClasses"] = len(mix.weights)
    out["FleetRadius"] = f"{mp.radius:g}"
    out["FleetSurveyHosts"] = mix.hosts
    out["FleetUnrepresentedPct"] = round(100 * mix.unrepresented)
    out["FleetNonXPct"] = round(100 * mix.non_x86)


def table() -> str:
    """Rows: class, logical CPUs, memory bucket (GiB), share of survey hosts (%)."""
    _, mix = fleet_mix()
    rows = ["% Generated by experiments.analysis.paper_inputs; do not edit."]
    for name, w in sorted(mix.weights.items()):
        hw = load_hw(name)
        label = name.replace("_", "\\_")
        rows.append(f"\\texttt{{{label}}} & {hw.cores} & {mem_bucket(hw.mem_gb):g} & {100 * w:.1f} \\\\")
    rows.append("\\bottomrule")
    return "\n".join(rows) + "\n"
