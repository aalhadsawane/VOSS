"""The calibrated fleet's survey mapping for the paper (plan V9.4, D-107, marker T14 in ``method.tex``): the weight of
each machine class, the share of hosts no calibrated machine represents well and the share that is not x86.

    uv run python -m experiments.analysis.fleet_mix      # needs the survey under data/traces; writes MIX

The survey is gitignored data, so the mapping is computed here once and committed as ``configs/machines_mix.yaml``
(with the survey's hash); ``experiments.analysis.paper_inputs`` reads only that file (macros in ``inputs.tex``, the
table ``fleet.tex``), as it reads the traces' provenance files.
"""

from __future__ import annotations

import hashlib
from pathlib import Path
from typing import Any

import yaml
from voss.core.config import load_config
from voss.core.paths import REPO_ROOT
from voss.world.machines import MachinesParams, load_hw, mem_bucket, survey_mix, survey_table

FLEET = REPO_ROOT / "configs" / "base.yaml"
MIX = REPO_ROOT / "configs" / "machines_mix.yaml"


def survey_path(mp: MachinesParams) -> Path:
    d = Path(mp.trace_root) / mp.survey / "hosts.parquet"
    return d if d.is_absolute() else REPO_ROOT / d


def compute() -> dict[str, Any]:
    """The mix of the fleet in ``configs/base.yaml`` from its survey (the data must be present)."""
    mp = MachinesParams.model_validate(load_config(FLEET).scenario.machines)
    hw = {b: load_hw(b) for b in sorted(set(mp.bundles))}
    mix = survey_mix(survey_table(mp), hw, mp.radius)
    return {
        "provenance": {"default": "trace", "note": "generated by experiments.analysis.fleet_mix (D-107); do not edit"},
        "survey": mp.survey,
        "input_sha256": hashlib.sha256(survey_path(mp).read_bytes()).hexdigest(),
        "radius": mp.radius,
        "hosts": mix.hosts,
        "unrepresented": round(mix.unrepresented, 6),
        "non_x86": round(mix.non_x86, 6),
        "classes": {
            n: {"threads": hw[n].cores, "mem_gib": mem_bucket(hw[n].mem_gb), "weight": round(w, 6)}
            for n, w in sorted(mix.weights.items())
        },
    }


def load_mix() -> dict[str, Any]:
    data: dict[str, Any] = yaml.safe_load(MIX.read_text())
    return data


def values(out: dict[str, float | int | str]) -> None:
    m = load_mix()
    out["FleetClasses"] = len(m["classes"])
    out["FleetRadius"] = f"{m['radius']:g}"
    out["FleetSurveyHosts"] = int(m["hosts"])
    out["FleetUnrepresentedPct"] = round(100 * m["unrepresented"])
    out["FleetNonXPct"] = round(100 * m["non_x86"])


def table() -> str:
    """Rows: class, logical CPUs, memory bucket (GiB), share of survey hosts (%)."""
    rows = ["% Generated by experiments.analysis.paper_inputs; do not edit."]
    for name, c in sorted(load_mix()["classes"].items()):
        label = name.replace("_", "\\_")
        rows.append(f"\\texttt{{{label}}} & {c['threads']} & {c['mem_gib']:g} & {100 * c['weight']:.1f} \\\\")
    rows.append("\\bottomrule")
    return "\n".join(rows) + "\n"


if __name__ == "__main__":
    MIX.write_text(yaml.safe_dump(compute(), sort_keys=False))
    print(f"wrote {MIX}")
