"""LaTeX macros for every number in the paper (docs/REVISION_PLAN.md V2, WRITING_SPEC.md §2): the manuscript never
contains a typed result. ``write({"DeadlineMetVoss": 0.951, ...}, path)`` emits
``\\newcommand{\\VDeadlineMetVoss}{0.95}``.
"""

from __future__ import annotations

import math
import re
from pathlib import Path

PREFIX = "V"
NAME = re.compile(r"^[A-Za-z]+$")


def fmt(x: float | int | str, digits: int = 2) -> str:
    """Two significant digits by default (WRITING_SPEC.md §8); integers and strings as they are."""
    if isinstance(x, str):
        return x
    if isinstance(x, int) or (isinstance(x, float) and x.is_integer() and abs(x) >= 10):
        return f"{int(x):,}".replace(",", "{,}")
    if not math.isfinite(x):
        raise ValueError(f"not a finite number: {x}")
    return f"{x:.{digits}g}"


def render(values: dict[str, float | int | str], digits: int = 2) -> str:
    lines = ["% Generated by experiments.analysis.macros; do not edit."]
    for name in sorted(values):
        if not NAME.match(name):
            raise ValueError(f"macro names are letters only (LaTeX): {name!r}")
        lines.append(f"\\newcommand{{\\{PREFIX}{name}}}{{{fmt(values[name], digits)}}}")
    return "\n".join(lines) + "\n"


def write(values: dict[str, float | int | str], path: Path, digits: int = 2) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(values, digits))
