def tab(exp: str) -> pd.DataFrame:
    return pd.read_csv(T / f"{exp}.csv")


def esc(s: object) -> str:
    return re.sub(r"([_&%#])", r"\\\1", str(s))


def ms(x: pd.Series | np.ndarray, nd: int = 2) -> str:
    """``mean ± half-width`` of the 95% bootstrap CI over seeds."""
    m, lo, hi = bootstrap_ci(np.asarray(x, dtype=float)[~np.isnan(np.asarray(x, dtype=float))])
    return f"{m:.{nd}f}{{\\scriptsize$\\pm${(hi - lo) / 2:.{nd}f}}}"


def rows(*cells: object) -> str:
    return " & ".join(str(c) for c in cells) + r" \\"


def tabular(spec: str, header: list[str], body: list[str], extra: str = "") -> str:
    head = " & ".join(f"\\textbf{{{h}}}" for h in header) + r" \\"
    return "\n".join(
        [
            f"\\begin{{tabular}}{{{spec}}}",
            r"\toprule",
            head,
            r"\midrule",
            extra,
            *body,
            r"\bottomrule",
            r"\end{tabular}",
            "",
        ]
    )


class Gen:
    """Accumulates macros and table fragments."""

    def __init__(self) -> None:
        self.macros: dict[str, str] = {}
        self.files: dict[str, str] = {}
        self.hyp = pd.read_csv(T / "hypotheses.csv")

    def mac(self, name: str, value: object) -> None:
        name = (
            name.replace("P99", "PNinetynine").replace("P50", "PFifty").replace("F0", "FZero")
        )  # no digits in macro names
        assert not re.search(r"\d", name), name
        self.macros[name] = str(value)

    def h(self, hid: str, cmp_: str, cell: str = "", metric: str = "p99_sync") -> pd.Series:
        d = self.hyp[(self.hyp["id"] == hid) & (self.hyp.cmp.str.startswith(cmp_)) & (self.hyp.metric == metric)]
        if cell:
            d = d[d.cell.fillna("").str.contains(cell, regex=False)]
        if len(d) != 1:
            raise KeyError(f"{hid} {cmp_} {cell}: {len(d)} rows")
        return d.iloc[0]

    def rel(self, name: str, hid: str, cmp_: str, cell: str = "", digits: int = 0, metric: str = "p99_sync") -> float:
        """Macro ``name`` = |relative effect| in percent; returns the signed value."""
        r = self.h(hid, cmp_, cell, metric)
        v = 100.0 * r.delta / r.base
        self.mac(name, f"{abs(v):.{digits}f}")
        return float(v)


def expect(cond: bool, msg: str) -> None:
    if not cond:
        raise AssertionError(f"the draft's claim no longer holds: {msg}")


UNICODE = {
    "α": r"$\alpha$",
    "θ": r"$\theta$",
    "Δ": r"$\Delta$",
    "≈": r"$\approx$",
    "×": r"$\times$",
    "≥": r"$\geq$",
    "≤": r"$\leq$",
    "→": r"$\rightarrow$",
    "—": "---",
    "−": "$-$",
    "·": r"$\cdot$",
    "σ": r"$\sigma$",
    "≪": r"$\ll$",
}


def latexify(text: str) -> str:
    """Replace the Unicode symbols the result tables use (the manuscript is pdfLaTeX)."""
    return "".join(UNICODE.get(c, c) for c in text)


def write(out: Path, g: Gen) -> None:
    out.mkdir(parents=True, exist_ok=True)
    lines = ["% Generated by experiments/paper_tex.py from paper/ and configs/calibration/; do not edit."]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(g.macros.items())]
    (out / "macros.tex").write_text("\n".join(lines) + "\n")
    for name, text in g.files.items():
        (out / name).write_text("% Generated by experiments/paper_tex.py; do not edit.\n" + latexify(text))
